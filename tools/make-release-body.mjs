// ---------------------------------------------------------------------------
// 生成 v0.2.5 Release 的正文 JSON
//
// 用 Node 明确写 UTF-8 文件，不经过 PowerShell 的编码转换，避免中文变问号。
//
// 输出：tools\ui\shots\release-body.json（UTF-8 无 BOM）
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const VERSION = `v${pkg.version}`;
const outDir = join(root, 'tools', 'ui', 'shots');
mkdirSync(outDir, { recursive: true });
const out = join(outDir, 'release-body.json');

const body = `## 修复：自动推进跑到一半自己停住

这一版主要是修两个「跑到一半突然断掉」的问题，都是在真实跑团过程中遇到的。

### 1. 502 网关抖动导致自动推进永久停止

跑团跑到一半，界面突然弹出：

\`\`\`
【KP 连接失败】HTTP 502 Bad Gateway
{"error":{"message":"模型 xxx 及降级目标全部失败：Loomy chat HTTP 502..."}}
系统
【自动推进已停止】KP 连接失败，检查模型配置后再继续。
\`\`\`

然后自动推进就彻底停了，只能手动重新打开开关。

问题在于 **502 是上游网关的瞬时故障，不是你的配置错了**——它往往几秒后自己就好了。
旧代码一次抖动就直接判定失败，还把自动推进开关永久关掉，等于把一次网络波动
当成了配置错误。

现在改成：

| 情况 | 旧行为 | 新行为 |
|---|---|---|
| 502 / 503 / 504 / 429 / 网络断开 | 立刻失败，自动推进永久停止 | **自动重试 2 次**（退避 0.8s → 1.6s），重试期间界面提示「正在自动重试」 |
| 重试后仍失败 | 甩一整段 HTML 给玩家看 | 说人话：「模型服务暂时不可用，上游网关故障，通常过一会儿会自己恢复」 |
| 401 / 403 / 404（密钥或模型名错） | 立刻失败 | 立刻失败（重试没用），并明确指出**该去设置里改什么** |
| 你主动点取消 | — | 立刻停止，绝不重试 |

重试只针对「等一会儿可能就好了」的错误。密钥填错、模型名写错这类问题重试一百次
也是同样结果，只会让你多等三倍时间才看到真正的错误，所以仍然立刻报错。

自动推进在连接失败时也不再永久关闭开关，只暂停；你点一下「推进」就能接着自动跑。

### 2. 「已达到自动推进上限（200 轮）」永久卡死

跑久了会看到：

\`\`\`
【自动推进已停止】已达到自动推进上限（200 轮）。
\`\`\`

然后**再也开不了自动推进**——点开关毫无反应，只能重开游戏。

这里有两个错：

- **算错了对象**：上限读的是「整局游戏轮数」，而不是「连续自动推进轮数」。
  一局玩到 200 轮就再也用不了自动推进，而 200 轮在 2 秒间隔下只要 7 分钟，
  正常玩一局必然撞上。
- **不可恢复**：上限被当成「终局」，点开关时直接拒绝开启，玩家没有任何恢复手段。

现在：

- 计数改成**连续自动推进轮数**，上限提到 1000 轮
- 你任何一次手动操作（点推进、开关、掷骰）都会把计数清零
- 真撞到上限也只是**暂停**并提示「手动推一次即可继续」，开关不会关掉

它现在只拦「没人管、模型一直空转」这一种情况，不会再误伤正常的长局。

## 顺带改进

- 自动推进间隔默认 2 秒，留出阅读时间
- 上游报错信息会翻译成中文说明，不再把整页 HTML 糊到界面上
- 重试期间界面有提示，不会看起来像卡死

## 已知限制

- 流式输出如果已经收到一部分内容后中断，不会重试——否则会把前半段重复
  推一遍，界面上出现两截拼接的乱码。这种情况会如实提示「流式输出中断」。
- 重试次数固定 2 次（共 3 次请求）。如果上游长时间不可用，还是需要等它恢复。
`;

writeFileSync(out, JSON.stringify({ tag_name: VERSION, name: VERSION, body }, null, 2), 'utf8');
console.log(`已生成 ${out}`);
console.log(`版本：${VERSION}`);
console.log(`正文长度：${body.length} 字符`);
