// ---------------------------------------------------------------------------
// 生成 v0.3.1 Release 的正文 JSON
//
// 用 Node 明确写 UTF-8 文件，不经过 PowerShell 的编码转换，避免中文变问号。
//
// 输出：tools\ui\shots\release-body.json（UTF-8 无 BOM）
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const VERSION = `v${pkg.version}`;
const outDir = join(root, 'tools', 'ui', 'shots');
mkdirSync(outDir, { recursive: true });
const out = join(outDir, 'release-body.json');

const body = `## 修复：长局卡顿 + 自动推进自己停住

这一版修两个都是「跑久了才出现」的问题。短局里碰不到，跑上几百轮就开始折磨人。

### 1. 跑团文本变长后界面卡死

跑到后期，输入框打字都有延迟，滚动像在拖泥带水，守密人输出时整屏卡住。

实测了一局跑到后期的存档：**10614 条消息、28416 个 DOM 节点、125 万字**。这些全部挂在页面上，而守密人输出是**流式**的——每来一小段文字，页面就要重新算一遍布局。等于每帧都要重排近三万个节点，帧率直接掉到个位数。

改法是**只渲染最近 200 条**：

| | 优化前 | 优化后 |
|---|---|---|
| DOM 节点 | 28,416 | **534** |
| 每帧重排节点 | 28,416 | 534 |

**缩减 53 倍，而且不再随局长度增长**——跑到一万条和跑到一千条一样流畅。

更早的消息没有丢，它们还在存档里（导出、存档、压缩都照旧），只是不挂在页面上。想看就点消息区顶部的 **「↑ 更早的记录」**，一次往前加载 200 条。

顺带做的几件事：

- **滚动不再触发全页重排**：原来的滚到底部会先读一次「内容总高度」再写滚动位置，这一读一写交替会让浏览器每次都强制重算布局。现在改成直接写一个必然超限的值让浏览器自己夹住，省掉那次读取。
- **屏外内容不渲染**：滚到哪才画哪。
- **单条消息的重排不外溢**：守密人输出时只有最后一条在变，其余上万条不该跟着重算。
- **超长局面自动关掉入场动画**：上万条消息同时播淡入动画会占满主线程。短局（400 条以内）保留动画，观感不变。

### 2. 手动点「推进」后自动推进就死了

开着自动推进，中途自己点了一次「推进」，然后自动推进就再也不动了——开关还亮着显示「自动推进 · 开」，但它永远不会再触发，只能关掉再打开。

原因是手动推进时会先把自动推进的定时器清掉（这是对的，避免两条线同时跑），但**跑完之后没有把它重新接上**。于是开关状态和实际行为脱节了。

现在手动推进跑完会自动接回定时器。如果那一刻正卡在「等你掷骰」，它会老实等着，不会抢跑。

## 顺带改进

- 自动推进默认间隔改为 **2 秒**，留出阅读时间

## 升级说明

直接下载新的 \`COC.exe\` 覆盖旧的即可，存档不受影响。第一次启动仍会静默解压约 10 秒。

## 已知限制

- 「更早的记录」是一次加载 200 条的，翻很久以前的剧情需要多点几次。这是有意的取舍：一次性渲染全部内容就会退回卡顿状态。
`;

writeFileSync(out, JSON.stringify({ tag_name: VERSION, name: VERSION, body }, null, 2), 'utf8');
console.log(`已生成 ${out}`);
console.log(`版本：${VERSION}`);
console.log(`正文长度：${body.length} 字符`);
